export type LocalizedString = Record<LanguageCode, string>;
export type LocalizedStringList = Record<LanguageCode, string[]>;

export interface CityRecord {
  id: string;
  name: LocalizedString;
  lat: number;
  lon: number;
  populationMillions: number;
  elevationM: number;
  aqi: number;
  pm25: number;
  co2PerCapita: number;
  renewablePct: number;
  waterQualityScore: number;
  tempAnomalyC: number;
  greenSpacePct: number;
  climateNote: LocalizedString;
  envNote: LocalizedString;
  strengths: LocalizedStringList;
  issues: LocalizedStringList;
  monthlyAqi: number[];
}

export interface CountryRecord {
  id: string;
  numericId: string; // matches world-atlas countries-110m.json id
  iso2: string;
  region: Exclude<RegionId, 'all'>;
  name: LocalizedString;
  capital: LocalizedString;
  populationMillions: number;
  areaKm2: number;
  aqi: number;
  pm25: number;
  co2PerCapita: number;
  forestCoverPct: number;
  renewablePct: number;
  tempAnomalyC: number;
  waterQualityScore: number;
  biodiversityScore: number;
  climateZone: LocalizedString;
  terrain: LocalizedString;
  geoDescription: LocalizedString;
  envDescription: LocalizedString;
  analysis: {
    strengths: LocalizedStringList;
    risks: LocalizedStringList;
    recommendations: LocalizedStringList;
    outlook2030: LocalizedString;
  };
  cities: CityRecord[];
}

export interface TimeSeriesPoint {
  year: number;
  co2: number;
  tempAnomalyC: number;
}

export interface RegionalAggregate {
  region: Exclude<RegionId, 'all'>;
  forestPct: number;
  renewablePct: number;
  meanAqi: number;
  timeSeries: TimeSeriesPoint[];
}

export interface NotificationItem {
  id: string;
  severity: StatusLevel;
  countryId: string;
  timestamp: LocalizedString;
  title: LocalizedString;
  body: LocalizedString;
  read: boolean;
}


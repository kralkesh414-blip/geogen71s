export function getStatusFromAqi(aqi: number, threshold = 100): StatusLevel {
  if (aqi >= threshold) return 'critical';
  if (aqi >= Math.round(threshold * 0.5)) return 'moderate';
  return 'good';
}

export function getCountryLayerColor(country: CountryRecord, layer: MapLayer): string {
  switch (layer) {
    case 'aqi': {
      if (country.aqi <= 35) return '#0d9488';
      if (country.aqi <= 60) return '#14b8a6';
      if (country.aqi <= 85) return '#d97706';
      return '#dc2626';
    }
    case 'co2': {
      if (country.co2PerCapita <= 3.5) return '#0d9488';
      if (country.co2PerCapita <= 8.0) return '#0284c7';
      if (country.co2PerCapita <= 13.0) return '#d97706';
      return '#dc2626';
    }
    case 'forest': {
      if (country.forestCoverPct >= 45) return '#15803d';
      if (country.forestCoverPct >= 25) return '#16a34a';
      if (country.forestCoverPct >= 10) return '#65a30d';
      return '#ca8a04';
    }
    case 'renewable': {
      if (country.renewablePct >= 60) return '#0f766e';
      if (country.renewablePct >= 35) return '#0d9488';
      if (country.renewablePct >= 20) return '#0284c7';
      return '#64748b';
    }
    case 'temp': {
      if (country.tempAnomalyC >= 1.75) return '#dc2626';
      if (country.tempAnomalyC >= 1.5) return '#ea580c';
      if (country.tempAnomalyC >= 1.35) return '#d97706';
      return '#0284c7';
    }
  }
}

